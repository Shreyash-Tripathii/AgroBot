#!/usr/bin/env python3
"""Generates worlds/agro_field.sdf: a seeded, reproducible crop-field world.

Layout (x forward, y left; the robot spawns at the origin in the headland):
  - crop rows run along +x starting at --field-start, spaced --row-spacing apart
  - a fence plus landmarks (shed, water tank, crates, tree) give SLAM/AMCL structure
  - ground truth labels: 1 cabbage, 2 tomato plant, 3 carrot (gz-sim-label-system)

  python3 generate_field_world.py --out ../worlds/agro_field.sdf --seed 7
"""
import argparse
import math
import random

CROPS = ['cabbage', 'tomato_plant', 'carrot']

HEADER = """<?xml version="1.0"?>
<!-- GENERATED by scripts/generate_field_world.py ({args}). Do not edit by hand. -->
<sdf version="1.9">
  <world name="{name}">
    <physics name="1ms" type="dart">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <plugin filename="gz-sim-navsat-system" name="gz::sim::systems::NavSat"/>

    <gravity>0 0 -9.81</gravity>
    <spherical_coordinates>
      <surface_model>EARTH_WGS84</surface_model>
      <world_frame_orientation>ENU</world_frame_orientation>
      <latitude_deg>{lat}</latitude_deg>
      <longitude_deg>{lon}</longitude_deg>
      <elevation>10.0</elevation>
      <heading_deg>0</heading_deg>
    </spherical_coordinates>

    <scene>
      <ambient>0.55 0.55 0.55 1</ambient>
      <background>0.62 0.78 0.92 1</background>
      <shadows>true</shadows>
    </scene>
    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 20 0 0 0</pose>
      <diffuse>0.95 0.92 0.85 1</diffuse>
      <specular>0.25 0.25 0.25 1</specular>
      <direction>-0.4 0.25 -0.9</direction>
    </light>

    <model name="ground">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>200 200</size></plane></geometry>
          <surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction></surface>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>200 200</size></plane></geometry>
          <material>
            <ambient>0.33 0.24 0.15 1</ambient>
            <diffuse>0.33 0.24 0.15 1</diffuse>
            <specular>0.02 0.02 0.02 1</specular>
          </material>
        </visual>
      </link>
    </model>
"""

def box(name, x, y, sx, sy, sz, color, yaw=0.0):
    return f"""    <model name="{name}"><static>true</static><pose>{x:.3f} {y:.3f} {sz/2:.3f} 0 0 {yaw:.4f}</pose>
      <link name="link">
        <collision name="c"><geometry><box><size>{sx} {sy} {sz}</size></box></geometry></collision>
        <visual name="v"><geometry><box><size>{sx} {sy} {sz}</size></box></geometry>
          <material><ambient>{color}</ambient><diffuse>{color}</diffuse></material></visual>
      </link></model>
"""

def cylinder(name, x, y, r, h, color):
    return f"""    <model name="{name}"><static>true</static><pose>{x:.3f} {y:.3f} {h/2:.3f} 0 0 0</pose>
      <link name="link">
        <collision name="c"><geometry><cylinder><radius>{r}</radius><length>{h}</length></cylinder></geometry></collision>
        <visual name="v"><geometry><cylinder><radius>{r}</radius><length>{h}</length></cylinder></geometry>
          <material><ambient>{color}</ambient><diffuse>{color}</diffuse></material></visual>
      </link></model>
"""

def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    p.add_argument('--out', default='../worlds/agro_field.sdf')
    p.add_argument('--name', default='agro_field')
    p.add_argument('--rows', type=int, default=6)
    p.add_argument('--plants', type=int, default=12, help='plants per row')
    p.add_argument('--row-spacing', type=float, default=0.75)
    p.add_argument('--plant-spacing', type=float, default=0.6)
    p.add_argument('--field-start', type=float, default=2.0, help='x of the first plant column')
    p.add_argument('--mix', type=float, default=0.15, help='chance a plant is a different crop')
    p.add_argument('--gap', type=float, default=0.05, help='chance a plant is missing')
    p.add_argument('--seed', type=int, default=7)
    p.add_argument('--lat', type=float, default=26.8467)
    p.add_argument('--lon', type=float, default=80.9462)
    a = p.parse_args()
    rnd = random.Random(a.seed)

    out = [HEADER.format(args=' '.join(f'{k}={v}' for k, v in sorted(vars(a).items())),
                         name=a.name, lat=a.lat, lon=a.lon)]

    # ---- crop rows --------------------------------------------------------
    length = (a.plants - 1) * a.plant_spacing
    for r in range(a.rows):
        y = (r - (a.rows - 1) / 2.0) * a.row_spacing
        row_crop = CROPS[r % len(CROPS)]
        for i in range(a.plants):
            if rnd.random() < a.gap:
                continue
            crop = rnd.choice([c for c in CROPS if c != row_crop]) if rnd.random() < a.mix else row_crop
            x = a.field_start + i * a.plant_spacing + rnd.uniform(-0.04, 0.04)
            yy = y + rnd.uniform(-0.04, 0.04)
            out.append(f"""    <include><uri>model://{crop}</uri><name>{crop}_r{r}_{i}</name>
      <pose>{x:.3f} {yy:.3f} 0 0 0 {rnd.uniform(0, 2 * math.pi):.3f}</pose></include>
""")

    # ---- fence ------------------------------------------------------------
    x0, x1 = -5.0, a.field_start + length + 2.5
    half_w = max(4.5, (a.rows - 1) * a.row_spacing / 2.0 + 2.5)
    wood = '0.55 0.42 0.25 1'
    out.append(box('fence_north', (x0 + x1) / 2, half_w, x1 - x0, 0.1, 0.5, wood))
    out.append(box('fence_south', (x0 + x1) / 2, -half_w, x1 - x0, 0.1, 0.5, wood))
    out.append(box('fence_west', x0, 0.0, 0.1, 2 * half_w, 0.5, wood))
    out.append(box('fence_east', x1, 0.0, 0.1, 2 * half_w, 0.5, wood))

    # ---- landmarks (asymmetric on purpose: SLAM/AMCL need unique features) ---
    out.append(box('shed', x0 + 1.5, half_w - 1.3, 1.6, 1.2, 1.4, '0.65 0.18 0.15 1'))
    out.append(box('crates', x0 + 1.2, -half_w + 1.1, 0.7, 0.5, 0.45, '0.60 0.45 0.20 1', yaw=0.35))
    out.append(cylinder('water_tank', x1 - 1.4, -half_w + 1.4, 0.5, 1.0, '0.25 0.45 0.70 1'))
    out.append(cylinder('tree_trunk', x1 - 1.3, half_w - 1.2, 0.12, 1.8, '0.35 0.22 0.10 1'))
    out.append(box('hay_bale', x0 + 2.3, 0.0, 0.8, 0.5, 0.5, '0.85 0.75 0.35 1', yaw=-0.2))

    out.append("  </world>\n</sdf>\n")
    with open(a.out, 'w') as f:
        f.write(''.join(out))
    n = sum(s.count('<include>') for s in out)
    print(f"wrote {a.out}: {a.rows} rows x {a.plants}, {n} plants, seed {a.seed}")

if __name__ == '__main__':
    main()
